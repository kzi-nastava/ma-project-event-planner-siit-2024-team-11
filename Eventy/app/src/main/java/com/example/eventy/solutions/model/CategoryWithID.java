package com.example.eventy.solutions.model;

import com.example.eventy.model.enums.Status;

public class CategoryWithID {
    private Long id;
    private String name;
    private String description;
    private Status status;

    public CategoryWithID() {}

    public CategoryWithID(Long id, String name, String description, Status status) {
        this.id = id;
        this.name = name;
        this.description = description;
        this.status = status;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public Status getStatus() {
        return status;
    }

    public void setStatus(Status status) {
        this.status = status;
    }
}
